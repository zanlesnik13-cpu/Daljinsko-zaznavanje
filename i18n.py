def get_lang() -> str:
    """Return the active UI language ('sl' or 'en') from Streamlit session state."""
    try:
        import streamlit as st

        lang = str(st.session_state.get("lang", "sl"))
        return lang if lang in TRANSLATIONS else "sl"
    except Exception:
        return "sl"


def t(key: str, lang: str | None = None, **kwargs: Any) -> str:
    """Translate a UI string key into the active language ('sl' or 'en')."""
    active = lang if (lang in TRANSLATIONS) else get_lang()
    text = TRANSLATIONS[active].get(key)
    if text is None:
        text = TRANSLATIONS["sl"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text
